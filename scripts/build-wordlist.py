#!/usr/bin/env python3
"""
Builds src/games/wordpop/words.js from the SCOWL lists in the `wordlist-english`
npm package (MIT wrapper, SCOWL licence: see src/games/wordpop/WORDS-LICENSE.txt).

    npm pack wordlist-english@1.2.1 && tar xzf wordlist-english-1.2.1.tgz
    python3 scripts/build-wordlist.py package/

Keeps lowercase ASCII words of 3–8 letters from the common tiers (10–50),
including both American and British spellings.
"""
import json
import os
import shutil
import sys

src = sys.argv[1]
out_dir = os.path.join(os.path.dirname(__file__), "..", "src", "games", "wordpop")
words = set()
for tier in (10, 20, 35, 40, 50):
    for kind in ("english", "american", "british"):
        path = os.path.join(src, f"{kind}-words-{tier}.json")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                words |= set(json.load(f))

# Slurs and strong profanity never score in a family game. Roots also block
# their inflections (e.g. -s, -ed, -er, -ing); only unambiguous roots are listed
# so ordinary words are unaffected.
BLOCKED_ROOTS = (
    "fuck", "shit", "cunt", "nigg", "fagg", "dyke", "kike", "chink", "tranny",
    "whore", "slut", "bitch", "twat", "wank", "retard", "cocksuck", "motherf", "jizz",
    "gook", "wetback", "coon", "honkie", "honky", "beaner", "raghead", "pussies", "pussy",
)
BLOCKED_EXACT = {"spic", "spics", "fag", "fags", "cum", "cums", "porn", "porno", "rape", "raped", "rapes", "rapist", "nazi", "nazis"}


def allowed(w):
    if w in BLOCKED_EXACT:
        return False
    return not any(w.startswith(root) for root in BLOCKED_ROOTS)


words = sorted(
    w
    for w in words
    if w.isascii() and w.isalpha() and w.islower() and 3 <= len(w) <= 8 and allowed(w)
)
with open(os.path.join(out_dir, "words.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build-wordlist.py from SCOWL (see WORDS-LICENSE.txt). Do not edit.\n")
    f.write(f"// {len(words)} words, 3–8 letters, space-separated.\n")
    f.write("export default " + json.dumps(" ".join(words)) + ";\n")
shutil.copy(os.path.join(src, "Copyright"), os.path.join(out_dir, "WORDS-LICENSE.txt"))
print(f"wrote {len(words)} words")
